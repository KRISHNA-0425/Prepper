/**
 * Returns a clone of the curated companies list.
 */
export const getCuratedProfiles = () => {
  return JSON.parse(JSON.stringify(CURATED_COMPANY_PROFILES));
};

/**
 * Finds a curated profile by company name or slug.
 */
export const findCuratedProfile = (nameOrSlug) => {
  if (!nameOrSlug || typeof nameOrSlug !== 'string') return null;
  const clean = nameOrSlug.toLowerCase().trim();
  return CURATED_COMPANY_PROFILES.find(
    (p) => p.slug === clean || p.name.toLowerCase() === clean
  ) || null;
};
